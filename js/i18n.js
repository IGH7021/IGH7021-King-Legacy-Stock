let currentLang = localStorage.getItem(LANG_KEY) || "th";

function t(key, vars) {
  let str = (I18N[currentLang] && I18N[currentLang][key]) || I18N.th[key] || key;
  if (vars) Object.keys(vars).forEach(k => { str = str.replace(`{${k}}`, vars[k]); });
  return str;
}

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem(LANG_KEY, lang);
  if (typeof refreshCompactNumberInputs === "function") refreshCompactNumberInputs();
  applyStaticTranslations();
  if (typeof renderProducts === "function") renderProducts();
  if (typeof renderSalesHistory === "function") renderSalesHistory();
  if (typeof renderDashboard === "function") renderDashboard();
  if (typeof renderReports === "function") renderReports();
  if (typeof renderUpdatesPage === "function") renderUpdatesPage();
  if (typeof window.refreshCommunityTranslations === "function") window.refreshCommunityTranslations();
  if (typeof window.refreshSupportRequestUi === "function") window.refreshSupportRequestUi();
  if (typeof window.refreshAdminKeyTranslations === "function") window.refreshAdminKeyTranslations();
  if (typeof window.refreshProfileTranslations === "function") window.refreshProfileTranslations();
  if (typeof window.refreshAuthTranslations === "function") window.refreshAuthTranslations();
}

function applyStaticTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.querySelectorAll(".radio > label[for^='rating-']").forEach(label => {
    label.title = t("review_stars", { count: label.htmlFor.slice("rating-".length) });
  });
  document.querySelectorAll(".lang-btn").forEach(b => b.classList.toggle("seg-active", b.dataset.lang === currentLang));
  document.getElementById("toggle-select-mode-btn") &&
    (document.getElementById("toggle-select-mode-btn").textContent = selectMode ? t("select_mode_btn_off") : t("select_mode_btn_on"));
}
